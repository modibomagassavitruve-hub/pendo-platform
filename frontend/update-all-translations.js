// Liste des langues à mettre à jour
const languages = ['en', 'fr', 'es', 'ar', 'de', 'pt', 'wo', 'bm', 'yo', 'ig', 'ha', 'ff', 'fon', 'tw', 'ee', 'ln', 'kg', 'sg', 'sw', 'am', 'af', 'zu', 'xh', 'sn', 'st', 'tn', 'ts', 'nd', 'ss'];

const localesDir = path.join(__dirname, 'src', 'locales');

// Fonction pour mettre à jour un fichier de langue
function updateLanguageFile(lang) {
  const filePath = path.join(localesDir, lang, 'translation.json');

  try {
    // Lire le fichier existant
    const fileContent = fs.readFileSync(filePath, 'utf8');
    const translations = JSON.parse(fileContent);

    // Ajouter la section exchange avec les traductions pour cette langue
    const exchangeTranslations = {};
    for (const [key, values] of Object.entries(newKeys.exchange)) {
      exchangeTranslations[key] = values[lang] || values.en; // Fallback to English if translation missing
    }

    translations.exchange = exchangeTranslations;

    // Écrire le fichier mis à jour
    fs.writeFileSync(filePath, JSON.stringify(translations, null, 2) + '\n', 'utf8');
    console.log(`✅ ${lang}: Fichier mis à jour avec succès`);

    return true;
  } catch (error) {
    console.error(`❌ Erreur pour ${lang}:`, error.message);
    return false;
  }
}

// Mettre à jour tous les fichiers
console.log('🚀 Début de la mise à jour des fichiers de traduction...\n');

let successCount = 0;
let failCount = 0;

for (const lang of languages) {
  if (updateLanguageFile(lang)) {
    successCount++;
  } else {
    failCount++;
  }
}

console.log(`\n✨ Mise à jour terminée!`);
console.log(`✅ Succès: ${successCount} fichiers`);
console.log(`❌ Échecs: ${failCount} fichiers`);
